/**
 * Builds the service worker (PLAN.md Phase 7, "offline play"). The build writes
 * sw.js with the exact list of files it produced, so the first visit caches the
 * whole game and later visits work offline. Saves live in IndexedDB, which the
 * service worker never touches, so updating the game can't lose a farm.
 *
 * Strategy (an "app shell"):
 * - install: cache every listed file under a cache named for this build;
 * - activate: delete caches from older builds;
 * - pages and files: from this build's cache, so the page always matches the
 *   worker that serves it; the network only for anything not cached.
 * A new build installs in the background and waits until the page asks it to
 * take over (the "new version is ready" banner), or until every tab is closed.
 */

/** Files the service worker should cache, relative to its own URL. */
export function precacheList(bundleFiles: readonly string[], publicFiles: readonly string[]): string[] {
  const keep = (f: string) => !f.endsWith('.map') && f !== 'sw.js' && !f.startsWith('.');
  return [...new Set(['./', 'index.html', ...bundleFiles.filter(keep), ...publicFiles.filter(keep)])].sort();
}

export function serviceWorkerSource(files: readonly string[], version: string): string {
  return `// Generated by the build (src/pwa/serviceWorker.ts). Do not edit.
const CACHE = ${JSON.stringify(`homestead-acres-${version}`)};
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('homestead-acres-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'skip-waiting') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    // The game's page from this build's cache (any query string), else the network.
    event.respondWith(
      caches
        .open(CACHE)
        .then((cache) => cache.match('index.html'))
        .then((cached) => cached || fetch(request)),
    );
    return;
  }

  // Everything the game needs was cached at install; anything else goes to the network.
  // ignoreVary: servers may send "Vary: Origin", and module scripts are requested
  // with an Origin header that the install-time requests didn't have, which
  // would otherwise miss the cache and break an older version once the server
  // has moved on.
  event.respondWith(
    caches
      .open(CACHE)
      .then((cache) => cache.match(request, { ignoreSearch: true, ignoreVary: true }))
      .then((cached) => cached || fetch(request)),
  );
});
`;
}
